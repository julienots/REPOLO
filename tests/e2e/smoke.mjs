// Test de fumée : menu → solo → lancement → quelques secondes de jeu → captures d'écran.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = process.env.BASE || 'http://localhost:8080';
const OUT = process.env.OUT || '.';
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto(BASE);
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/01-menu.png` });
await page.click('[data-action="solo"]');
await page.waitForSelector('#screen-lobby.active', { timeout: 5000 });
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/02-lobby.png` });
await page.click('#btn-start');
await page.waitForSelector('#screen-game.active', { timeout: 5000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/03-game.png` });
await page.mouse.move(900, 300);
await page.keyboard.down('KeyW'); await page.waitForTimeout(1200); await page.keyboard.up('KeyW');
await page.keyboard.down('KeyD'); await page.waitForTimeout(1500); await page.keyboard.up('KeyD');
await page.keyboard.press('KeyE');
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/04-game-moved.png` });
const state = await page.evaluate(() => ({ screen: window.app.screen, me: window.app.game?.me && { x: window.app.game.me.x, y: window.app.game.me.y, st: window.app.game.me.st }, fps: window.app.renderer.fps, players: window.app.game?.last?.players.length, monsters: window.app.game?.last?.monsters.length, items: window.app.game?.last?.items.length }));
console.log(JSON.stringify(state));
console.log(errors.length ? errors.join('\n') : 'AUCUNE ERREUR CONSOLE');
await browser.close();
